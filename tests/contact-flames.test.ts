import assert from 'node:assert/strict'
import { Scene, Texture, Sprite } from 'three'
import { Body, ContactEquation } from 'cannon-es'
import { createContactFlames } from '../src/app/dice/contactFlames'

const scene = new Scene(), floor = new Body(), die = new Body({ mass: 1 })
const flames = createContactFlames(scene, floor, new Texture())
const contact = new ContactEquation(die, floor)
contact.rj.set(3, 0, 4)
die.velocity.set(2, 0, 0)
const visible = () => scene.children.filter((p): p is Sprite => p instanceof Sprite && p.visible)
assert.equal(flames.update(0.016, [], true), false, 'No airborne trail')
flames.update(0.016, [new ContactEquation(die, new Body())], true)
assert.equal(visible().length, 0, 'Only the floor emits')
flames.update(0.016, [contact, contact], true)
assert.equal(visible().length, 2, 'Multiple contact points are rate limited per die')
assert.ok(visible().every(p => Math.abs(p.position.x - 3) < 0.1 && p.position.z === 4), 'Use actual floor contact')
flames.update(0.6, [], true)
assert.equal(visible().length, 2, 'Trail lasts beyond the initial contact')
assert.ok(visible().every(p => p.material.opacity > 0.5 && p.scale.x > 0.5), 'Flames remain prominent after 600ms')
flames.update(1.5, [], true)
assert.equal(visible().length, 0, 'Trail fades after the roll')
die.sleep()
flames.update(0.1, [contact], true)
assert.equal(visible().length, 0, 'Resting dice do not emit')
die.wakeUp(); die.velocity.set(2, 0, 0)
for (let i = 0; i < 100; i++) flames.update(0.05, [contact], true)
assert.equal(scene.children.length, 192, 'Particle allocation stays bounded')
assert.ok(visible().length > 0)
flames.update(0.016, [contact], false)
assert.equal(visible().length, 0, 'Reduced motion / hidden page clears the effect')
flames.update(0.1, [contact], true)
flames.clear()
assert.equal(visible().length, 0, 'Preparing another roll clears particles')
flames.dispose()
assert.equal(scene.children.length, 0)
console.log('Contact flames: floor contact, throttle, fading, rest, capacity, reduced motion and cleanup passed.')
